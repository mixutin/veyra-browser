const{contextBridge,ipcRenderer}=require("electron");
contextBridge.exposeInMainWorld("veyra",{
state:()=>ipcRenderer.invoke("browser:state"),
onState:cb=>ipcRenderer.on("browser:state",(_e,s)=>cb(s)),
newTab:()=>ipcRenderer.send("tab:new"),
switchTab:id=>ipcRenderer.send("tab:switch",id),
closeTab:id=>ipcRenderer.send("tab:close",id),
go:value=>ipcRenderer.send("nav:go",value),
back:()=>ipcRenderer.send("nav:back"),
forward:()=>ipcRenderer.send("nav:forward"),
reload:()=>ipcRenderer.send("nav:reload"),
switchWorkspace:id=>ipcRenderer.send("workspace:switch",id),
newWorkspace:name=>ipcRenderer.invoke("workspace:new",name),
toggleSplit:()=>ipcRenderer.send("split:toggle"),
toggleShield:()=>ipcRenderer.invoke("shield:toggle"),
sleepInactive:()=>ipcRenderer.invoke("tab:sleep-inactive"),
reopenClosed:()=>ipcRenderer.invoke("tab:reopen-closed"),
setResourcePreset:name=>ipcRenderer.invoke("resources:preset",name),
setResourcePolicy:next=>ipcRenderer.invoke("resources:set",next),
bookmarks:()=>ipcRenderer.invoke("library:bookmarks"),
bookmarkCurrent:()=>ipcRenderer.invoke("library:bookmark-current"),
history:()=>ipcRenderer.invoke("library:history"),
scanMigration:()=>ipcRenderer.invoke("migration:scan"),
importProfile:source=>ipcRenderer.invoke("migration:import",source)
});